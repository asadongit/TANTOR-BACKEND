import os
import logging
from fpdf import FPDF
from langchain_core.tools import tool
from langchain_core.runnables.config import RunnableConfig
from Apps.AgentMesh.Schema.ToolSchema import ToolMeta
from Apps.AgentMesh.Core.ToolRegistry import registry

logger = logging.getLogger(__name__)

@tool
def export_as_pdf(content: str, filename: str, config: RunnableConfig = None):
    """
    Converts search results or notes into a professional PDF document.
    Saves the f ile to the agent's virtual filesystem and returns a download signal.
    
    Args:
        content: The text/markdown content to be converted to PDF.
        filename: The desired filename (e.g. 'search_report.pdf').
        config: System context (injected automatically).
    """
    try:
        from Apps.AgentMesh.Config import settings
        if not filename.endswith(".pdf"):
            filename += ".pdf"

        # 1. Resolve storage path
        configurable = config.get("configurable", {}) if config else {}
        thread_id = configurable.get("thread_id", "default")
        
        # We use the official exports mount path from Config.py
        root_dir = settings.EXPORTS_MOUNT
        dest_dir = os.path.join(root_dir, thread_id)
        os.makedirs(dest_dir, exist_ok=True)
        
        file_path = os.path.join(dest_dir, filename)

        # 2. Generate PDF with xhtml2pdf & Premium Styling
        import markdown
        from xhtml2pdf import pisa
        import io
        
        # Sanitize Unicode characters that cause 'black boxes' in PDF (Helvetica fallback)
        # Replacing fancy dashes and non-breaking spaces with standard ASCII
        sanitized_content = content.replace('\u2013', '-').replace('\u2014', '--') \
                                   .replace('\u2011', '-').replace('\u00a0', ' ') \
                                   .replace('\u2022', '*') # Bullet points
        
        # Convert Markdown to HTML with Tables support
        html_content = markdown.markdown(sanitized_content, extensions=['tables', 'fenced_code', 'nl2br'])
        
        # Premium CSS Design System
        premium_css = """
        <style>
            @page {
                size: a4;
                margin: 2cm;
            }
            body {
                font-family: Helvetica, Arial, sans-serif;
                font-size: 11pt;
                color: #333;
                line-height: 1.5;
            }
            h1 {
                color: #B91C1C; /* Professional Red */
                font-size: 24pt;
                border-bottom: 2px solid #EEE;
                padding-bottom: 10px;
                margin-bottom: 20px;
            }
            h2 {
                color: #1F2937;
                font-size: 18pt;
                margin-top: 30px;
            }
            h3 {
                color: #4B5563;
                font-size: 14pt;
            }
            table {
                width: 100%;
                border-collapse: collapse;
                margin: 20px 0;
            }
            th {
                background-color: #F3F4F6;
                color: #111827;
                font-weight: bold;
                padding: 10px;
                border: 1px solid #E5E7EB;
                text-align: left;
            }
            td {
                padding: 10px;
                border: 1px solid #E5E7EB;
                vertical-align: top;
            }
            tr:nth-child(even) {
                background-color: #FAFAFA;
            }
            code {
                background-color: #F3F4F6;
                padding: 2px 4px;
                border-radius: 4px;
                font-family: Courier, monospace;
            }
            pre {
                background-color: #F3F4F6;
                padding: 15px;
                border-radius: 8px;
                display: block;
            }
            .footer {
                text-align: center;
                font-size: 9pt;
                color: #9CA3AF;
                margin-top: 50px;
            }
        </style>
        """
        
        full_html = f"""
        <html>
            <head>
                <meta charset="UTF-8">
                {premium_css}
            </head>
            <body>
                {html_content}
                <div class="footer">Generated by AgentMesh Intelligence Platform • 2026</div>
            </body>
        </html>
        """
        
        # Write to file
        with open(file_path, "wb") as f:
            pisa_status = pisa.CreatePDF(full_html, dest=f)
        
        if pisa_status.err:
            raise Exception("Failed to render PDF with pisa")
        
        logger.info(f"Premium PDF exported: {file_path}")
        
        # 3. Return a helpful message with a direct download link
        # Note: The /exports path is mounted as static in main.py
        download_url = f"/exports/{thread_id}/{filename}"
        return f"Successfully generated report. You can download it here: [{filename}]({download_url})"
        
    except Exception as e:
        logger.error(f"Failed to export PDF: {e}")
        return f"Error generating PDF: {str(e)}"

# Register the tool
registry.register(
    export_as_pdf,
    ToolMeta(
        name="export_as_pdf",
        display_name="Export to PDF",
        description="Convert search notes or research into a downloadable PDF document.",
        category="Export",
        package="built-in",
        version="1.0.0"
    )
)
